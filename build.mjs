// Build the browser half of the NestJS Assistant bundle.
//
// The Harness Client module loader loads exactly one `./client` artifact whose
// factory receives only the browser module table (`require('react')`). Plain
// relative imports are not available there, so the source is kept as ordered
// plain-script fragments under `src/` and concatenated into `client.js`.
//
// Usage: `node build.mjs`
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));

/** Concatenation order: data, helpers, chat plumbing, views, styles, shell, registration. */
const PARTS = [
	'src/00-dicts.js',
	'src/01-utils.js',
	'src/02-glyphs.js',
	'src/03-chat.js',
	'src/04-styles-base.js',
	'src/views/knowledge.js',
	'src/views/enterprise-map.js',
	'src/views/learning-route.js',
	'src/views/playground.js',
	'src/styles/knowledge.js',
	'src/styles/enterprise-map.js',
	'src/styles/learning-route.js',
	'src/styles/playground.js',
	'src/panel.js',
	'src/apply.js'
];

/** Fragments must be plain scripts: no module syntax may leak into the factory. */
const FORBIDDEN = [/^\s*import\s/m, /^\s*export\s/m, /\brequire\s*\(/m, /<\/script>/i];

const chunks = [];
for (const part of PARTS) {
	const file = path.join(root, part);
	const source = fs.readFileSync(file, 'utf8');
	for (const pattern of FORBIDDEN) {
		if (pattern.test(source)) throw new Error(part + ' contains forbidden syntax: ' + String(pattern));
	}
	chunks.push('// ---- ' + part + ' ----\n' + source.trimEnd());
}

const body = chunks.join('\n\n');

/** Output target: `node build.mjs --out <file>` lets parallel agents build in isolation. */
const outIndex = process.argv.indexOf('--out');
const outPath = outIndex >= 0 && typeof process.argv[outIndex + 1] === 'string' && process.argv[outIndex + 1] !== ''
	? path.resolve(process.cwd(), process.argv[outIndex + 1])
	: path.join(root, 'client.js');
const output = `/* Generated by build.mjs — edit files under src/ instead. */
window.__ModuleLoader__.load({
	id: '@local/nest-assistant',
	factory(require) {
		const React = require('react');
		const h = React.createElement;

${body}

		return { inject, apply };
	}
});
`;

fs.writeFileSync(outPath, output);
console.log('client.js written:', outPath, output.length, 'bytes,', output.split('\n').length, 'lines');
